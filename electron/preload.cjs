const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('speakbridge', {
  bootstrap: () => ipcRenderer.invoke('bootstrap'),
  saveSettings: value => ipcRenderer.invoke('settings:save', value),
  testConnection: () => ipcRenderer.invoke('connection:test'),
  checkEngines: settings => ipcRenderer.invoke('engines:check', settings),
  detectEngines: () => ipcRenderer.invoke('engines:detect'),
  prepareModel: () => ipcRenderer.invoke('model:prepare'),
  start: options => ipcRenderer.invoke('session:start', options),
  stop: () => ipcRenderer.invoke('session:stop'),
  dictationPermission: prompt => ipcRenderer.invoke('dictation:permission', prompt),
  dictationStatus: prompt => ipcRenderer.invoke('dictation:status', prompt),
  saveDictationPreferences: value => ipcRenderer.invoke('dictation:preferences', value),
  warmDictation: () => ipcRenderer.invoke('dictation:warm'),
  finishDictation: () => ipcRenderer.invoke('dictation:finish'),
  armDictationInput: kind => ipcRenderer.invoke('dictation:arm-input', kind),
  insertArmedDictation: () => ipcRenderer.invoke('dictation:insert-armed'),
  dictationLevel: level => ipcRenderer.send('dictation:level', level),
  cancelDictation: message => ipcRenderer.invoke('dictation:cancel', message),
  copyDictation: () => ipcRenderer.invoke('dictation:copy'),
  hideDictation: () => ipcRenderer.invoke('dictation:hide'),
  clearDictation: id => ipcRenderer.invoke('dictation:clear', id),
  audio: bytes => ipcRenderer.send('audio:chunk', bytes),
  listSessions: () => ipcRenderer.invoke('history:list'),
  deleteSession: id => ipcRenderer.invoke('history:delete', id),
  deleteNotes: id => ipcRenderer.invoke('history:delete-notes', id),
  deleteSessions: ids => ipcRenderer.invoke('history:delete-many', ids),
  deleteNotesMany: ids => ipcRenderer.invoke('history:delete-notes-many', ids),
  updateSession: (id, patch) => ipcRenderer.invoke('history:update', id, patch),
  exportSession: (id, format) => ipcRenderer.invoke('history:export', id, format),
  copySession: id => ipcRenderer.invoke('history:copy', id),
  retryTranslation: id => ipcRenderer.invoke('history:retry', id),
  makeNotes: (id, language) => ipcRenderer.invoke('history:notes', id, language),
  notesStatus: id => ipcRenderer.invoke('history:notes-status', id),
  notesPlan: (id, language) => ipcRenderer.invoke('history:notes-plan', id, language),
  cancelNotes: id => ipcRenderer.invoke('history:notes-cancel', id),
  showOverlay: show => ipcRenderer.invoke('overlay:show', show),
  hideOverlay: () => ipcRenderer.invoke('overlay:hide'),
  onEvent: callback => { const listener = (_event, message) => callback(message); ipcRenderer.on('bridge:event', listener); return () => ipcRenderer.removeListener('bridge:event', listener); },
});
