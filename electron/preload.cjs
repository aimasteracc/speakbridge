  screenDelete: (kind, ids) => ipcRenderer.invoke('screen:delete', kind, ids),
  toolbarAction: command => ipcRenderer.invoke('toolbar:action', command),
  shortcutsGet: () => ipcRenderer.invoke('shortcuts:get'),
  shortcutsSave: bindings => ipcRenderer.invoke('shortcuts:save', bindings),
  captureKeys: enabled => ipcRenderer.invoke('capture:keys', enabled),
  clipboardList: () => ipcRenderer.invoke('clipboard:list'),
